CREATE OR REPLACE FUNCTION "public"."match_chunks"("query_embedding" "public"."vector", "match_count" integer) RETURNS TABLE("content" "text", "document_id" "uuid", "chunk_index" integer, "similarity" double precision)
    LANGUAGE "sql" STABLE
    AS $$
  select
    dc.content,
    dc.document_id,
    dc.chunk_index,
    1 - (dc.embedding <=> query_embedding) as similarity
  from public.document_chunks dc
  order by dc.embedding <=> query_embedding
  limit match_count;
$$;


