CREATE OR REPLACE FUNCTION "public"."match_chunks_json"("query_embedding" "jsonb", "match_count" integer) RETURNS TABLE("content" "text", "document_id" "uuid", "chunk_index" integer, "similarity" double precision)
    LANGUAGE "sql" STABLE SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
  with q as (
    select (
      '[' ||
      string_agg(elem, ',') ||
      ']'
    )::vector as v
    from jsonb_array_elements_text(query_embedding) as t(elem)
  )
  select
    dc.content,
    dc.document_id,
    dc.chunk_index,
    1 - (dc.embedding <=> q.v) as similarity
  from public.document_chunks dc
  cross join q
  order by dc.embedding <=> q.v
  limit match_count;
$$;


